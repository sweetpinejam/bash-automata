#!/usr/bin/env python3
"""State assertion test for Mission 2.05: The Parallel Map-Reduce Stream."""
import json
import os
import subprocess
import sys
from pathlib import Path


def log(msg: str):
    print(f"  [VERIFY] {msg}")


def fail(msg: str):
    print(f"  [FAIL] {msg}", file=sys.stderr)
    sys.exit(1)


def main():
    workspace = Path(os.environ.get("AUTOMATA_WORKSPACE", "."))
    orch_sh = workspace / "orchestrator.sh"
    metrics_json = workspace / "final_metrics.json"

    if not orch_sh.exists():
        fail("Missing required script: orchestrator.sh")

    # Clean previous run state
    if metrics_json.exists():
        metrics_json.unlink()
    for tsv in workspace.glob("summary_part_*.tsv"):
        tsv.unlink()

    log("Executing map-reduce pipeline across 4 partitions in parallel...")
    proc = subprocess.run(
        ["bash", str(orch_sh)],
        cwd=str(workspace),
        capture_output=True,
        text=True,
        timeout=10,
    )

    if proc.returncode != 0:
        fail(f"orchestrator.sh failed (exit code {proc.returncode}).\nStderr: {proc.stderr.strip()}")

    if "ORCHESTRATION_COMPLETE" not in proc.stdout:
        fail("orchestrator.sh did not complete cleanly or emit 'ORCHESTRATION_COMPLETE'.")

    log("Auditing final aggregated metrics ledger...")
    if not metrics_json.exists():
        fail("final_metrics.json was not generated by reducer!")

    try:
        metrics = json.loads(metrics_json.read_text(encoding="utf-8"))
    except Exception as e:
        fail(f"Failed to parse final_metrics.json: {e}")

    partitions = metrics.get("partitions", [])
    total_events = metrics.get("total_events", 0)
    total_success = metrics.get("total_success", 0)
    total_errors = metrics.get("total_errors", 0)

    log(f"Partitions captured by reducer: {len(partitions)}/4 ({partitions})")
    log(f"Total events aggregated: {total_events}/400 (Expected: 360 ok, 40 err)")

    if len(partitions) < 4:
        fail(f"Data loss detected! Only {len(partitions)} of 4 partitions were aggregated by the reducer. Premature barrier wait!")

    if total_events != 400:
        fail(f"Expected exactly 400 total events, but recorded {total_events}.")

    if total_success != 360 or total_errors != 40:
        fail(f"Metric counts incorrect! Expected 360 success / 40 errors, got {total_success} / {total_errors}.")

    log("ALL MAP-REDUCE BARRIER ASSERTIONS PASSED")
    sys.exit(0)


if __name__ == "__main__":
    main()
